def parse_stars_int(star_str: str) -> int:
    if not star_str:
        return 0
    clean = str(star_str).strip().lower().replace("★", "").replace(",", "")
    match = re.search(r'([0-9\.]+)\s*(k?)', clean)
    if not match:
        return 0
    num = float(match.group(1))
    if match.group(2) == 'k':
        num *= 1000
    return int(num)

def format_stars_text(stars_num: int) -> str:
    if stars_num >= 1000:
        return f"{stars_num/1000:.1f}k"
    return str(stars_num)

