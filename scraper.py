def scrape_topgit_section(section: str) -> List[Dict[str, Any]]:
    url_map = {
        "trending_daily": "https://topgit.dev/trending/daily",
        "trending_weekly": "https://topgit.dev/trending/weekly",
        "trending_monthly": "https://topgit.dev/trending/monthly",
        "recently_added": "https://topgit.dev/",
        "featured_reviews": "https://topgit.dev/"
    }
    url = url_map.get(section, "https://topgit.dev/trending/daily")
    
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept-Language": "en-US,en;q=0.9,vi;q=0.8"})
    try:
        with urllib.request.urlopen(req, timeout=8) as resp:
            html = resp.read().decode("utf-8", errors="ignore")
            soup = BeautifulSoup(html, "html.parser")
            repo_links = soup.find_all("a", href=re.compile(r'/repo/([a-zA-Z0-9_\-\.]+/[a-zA-Z0-9_\-\.]+)'))
            repos = []
            seen = set()
            for a in repo_links:
                href = a.get("href", "")
                m = re.search(r'/repo/([a-zA-Z0-9_\-\.]+/[a-zA-Z0-9_\-\.]+)', href)
                if not m: continue
                repo_name = m.group(1).strip()
                if repo_name in seen: continue
                seen.add(repo_name)

                parent = a.find_parent(["div", "li", "article"]) or a
                text = parent.get_text(separator=" ")
                star_match = re.search(r'★\s*([0-9\.]+[kK]?)', text)
                stars_text = star_match.group(1) if star_match else "0"
                stars_int = parse_stars_int(stars_text)
                growth_match = re.search(r'\+([0-9\.]+[kK]?/d)', text)
                stars_growth = f"+{growth_match.group(1)}" if growth_match else ""

                repos.append({
                    "repo_name": repo_name,
                    "title": repo_name.split("/")[-1],
                    "description": text[:250],
                    "stars": stars_int,
                    "stars_text": stars_text,
                    "stars_growth": stars_growth,
                    "language": "",
                    "source_platform": "topgit",
                    "source_section": section,
                    "is_reviewed": "Reviewed" in text or "✓" in text,
                    "tags": []
                })
            if repos:
                return repos
    except Exception:
        pass

    return [r for r in TOPGIT_SEEDS if r.get("source_section") == section] or TOPGIT_SEEDS

