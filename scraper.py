    """
    Yields repository items one-by-one as soon as each thread finishes.
    Powers real-time Server-Sent Events (SSE) so users see cards immediately!
    """
    tasks = []
    for sec in ["trending_daily", "trending_weekly", "trending_monthly", "recently_added", "featured_reviews"]:
        tasks.append(("topgit", sec))
    for topic in GITHUB_TOPIC_MAPPING.keys():
        tasks.append(("github", topic))

    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_task = {}
        for platform, target in tasks:
            if platform == "topgit":
                future = executor.submit(scrape_topgit_section, target)
            else:
                future = executor.submit(scrape_github_search, target, github_token)
            future_to_task[future] = (platform, target)

        for future in as_completed(future_to_task):
            try:
                items = future.result()
                if items:
                    for item in items:
                        yield item
            except Exception as e:
                pass
